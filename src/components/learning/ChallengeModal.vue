<script setup lang="ts">
import { computed, onBeforeUnmount, ref, watch } from 'vue'
import {
  ArrowRight,
  Headphones,
  Keyboard,
  Volume2,
  X,
} from 'lucide-vue-next'

import type {
  Challenge,
  ChallengeResult,
} from '@/types/learning'

import QuestionOptions from './QuestionOptions.vue'
import WritingChallenge from './WritingChallenge.vue'
import AnswerFeedback from './AnswerFeedback.vue'

const props = defineProps<{
  challenge: Challenge
  result: ChallengeResult | null
}>()

const emit = defineEmits<{
  submit: [answer: string]
  close: []
}>()

const answer = ref('')

const isListening = computed(
  () => props.challenge.skill === 'listening',
)

const canSubmit = computed(
  () => !props.result && answer.value.trim().length > 0,
)

watch(
  () => props.challenge.id,
  () => {
    answer.value = ''
  },
)

function playAudio(): void {
  if (!('speechSynthesis' in window)) return

  window.speechSynthesis.cancel()

  const utterance = new SpeechSynthesisUtterance(
    props.challenge.audioText ?? props.challenge.question,
  )

  utterance.lang = 'en-US'
  utterance.rate = 0.85

  window.speechSynthesis.speak(utterance)
}

function handleSubmit(): void {
  if (!canSubmit.value) return

  emit('submit', answer.value.trim())
}

function handleClose(): void {
  if (!props.result) return

  emit('close')
}

onBeforeUnmount(() => {
  if ('speechSynthesis' in window) {
    window.speechSynthesis.cancel()
  }
})
</script>

<template>
  <div
    class="fixed inset-0 z-50 flex items-center justify-center overflow-y-auto bg-black/80 p-4 backdrop-blur-sm"
  >
    <section
      class="my-auto w-full max-w-xl overflow-hidden rounded-3xl border border-white/10 bg-[#0d1324] shadow-2xl"
      role="dialog"
      aria-modal="true"
      aria-labelledby="challenge-title"
    >
      <header class="flex items-center justify-between border-b border-white/10 px-6 py-5">
        <div class="flex items-center gap-3">
          <div class="rounded-xl bg-purple-400/10 p-3 text-purple-300">
            <Headphones
              v-if="isListening"
              :size="20"
            />

            <Keyboard
              v-else
              :size="20"
            />
          </div>

          <div>
            <p class="text-xs font-bold uppercase tracking-widest text-purple-300">
              {{ challenge.skill }} challenge
            </p>

            <h2
              id="challenge-title"
              class="font-bold text-white"
            >
              {{ challenge.title }}
            </h2>
          </div>
        </div>

        <button
          v-if="result"
          type="button"
          class="rounded-lg p-2 text-slate-400 transition hover:bg-white/10 hover:text-white"
          aria-label="Close challenge"
          @click="handleClose"
        >
          <X :size="20" />
        </button>
      </header>

      <div class="space-y-6 p-6">
        <div>
          <div class="mb-3 flex flex-wrap items-center gap-2">
            <span class="rounded-full bg-purple-400/10 px-3 py-1 text-xs font-bold capitalize text-purple-300">
              {{ challenge.difficulty }}
            </span>

            <span class="text-xs text-slate-400">
              {{ challenge.instruction }}
            </span>
          </div>

          <h3 class="text-xl font-black leading-relaxed text-white">
            {{ challenge.question }}
          </h3>
        </div>

        <div
          v-if="isListening"
          class="flex items-center justify-between rounded-2xl border border-white/10 bg-white/5 p-4"
        >
          <div>
            <p class="font-bold text-white">
              Listen carefully
            </p>

            <p class="mt-1 text-xs text-slate-500">
              Audio is generated by your browser.
            </p>
          </div>

          <button
            type="button"
            class="rounded-xl bg-emerald-400 p-3 text-slate-950 transition hover:bg-emerald-300"
            aria-label="Play audio"
            @click="playAudio"
          >
            <Volume2 :size="20" />
          </button>
        </div>

        <!-- Multiple choice -->
        <QuestionOptions
        v-if="challenge.type === 'multiple-choice'"
        v-model="answer"
        :options="challenge.options ?? []"
        :disabled="Boolean(result)"
        />

        <!-- Writing -->
        <WritingChallenge
        v-else-if="challenge.type === 'writing'"
        v-model="answer"
        :min-words="challenge.minWords ?? 1"
        :keywords="challenge.requiredKeywords ?? []"
        :disabled="Boolean(result)"
        @submit="handleSubmit"
        />

        <AnswerFeedback
          v-if="result"
          :result="result"
        />

        <button
          v-if="!result"
          type="button"
          :disabled="!canSubmit"
          class="flex w-full items-center justify-center gap-2 rounded-xl bg-emerald-400 px-5 py-3.5 font-black text-slate-950 transition hover:bg-emerald-300 disabled:cursor-not-allowed disabled:opacity-40"
          @click="handleSubmit"
        >
          Submit answer
          <ArrowRight :size="18" />
        </button>

        <button
          v-else
          type="button"
          class="flex w-full items-center justify-center gap-2 rounded-xl bg-emerald-400 px-5 py-3.5 font-black text-slate-950 transition hover:bg-emerald-300"
          @click="handleClose"
        >
          Continue game
          <ArrowRight :size="18" />
        </button>
      </div>
    </section>
  </div>
</template>